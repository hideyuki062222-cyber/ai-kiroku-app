import fs from 'node:fs';
import assert from 'node:assert/strict';
const sql=fs.readFileSync(new URL('../database/recruitment_head_office_draft.sql',import.meta.url),'utf8');
for(const table of ['admins','settings','locations','templates','jobs','applicants','audit_logs'])assert(sql.includes(`ALTER TABLE public.recruitment_${table} ENABLE ROW LEVEL SECURITY;`));
assert(!/ALTER\s+TABLE\s+(?!public\.recruitment_|recruitment_private\.)/i.test(sql));
assert(!/CREATE\s+(?:OR\s+REPLACE\s+)?FUNCTION\s+(?!public\.recruitment_|recruitment_private\.)/i.test(sql));
assert(sql.includes('security_invoker=true'));
assert(sql.includes('REVOKE ALL ON FUNCTION public.recruitment_receive(jsonb,text,text) FROM PUBLIC,anon,authenticated'));
assert(!/GRANT\s+(?:ALL|INSERT|UPDATE).*?ON public\.recruitment_admins TO authenticated/i.test(sql));
console.log('SQL scope and fail-closed static checks passed. Run database.cjs for RLS behavior.');
